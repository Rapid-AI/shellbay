const DICTS: Record<Lang, Dict> = { en, ru, es, zh, ja, de }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? en
  let s = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]))
  }
  return s
}

export interface I18n {
  lang: Lang
  t: (key: string, vars?: Record<string, string | number>) => string
}

export const I18nContext = createContext<I18n>({ lang: DEFAULT_LANG, t: (k) => k })

export const useI18n = () => useContext(I18nContext)

const LANG_STORAGE_KEY = 'shellbay_lang'

export function loadStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY) ?? localStorage.getItem('harbor_lang')
    if (v && (LANGS as { code: string }[]).some((l) => l.code === v)) return v as Lang
  } catch { /* ignore */ }
  return DEFAULT_LANG
}

export function storeLang(lang: Lang) {
  try { localStorage.setItem(LANG_STORAGE_KEY, lang) } catch { /* ignore */ }
}
